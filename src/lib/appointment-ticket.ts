  const staffName = String(ctx.staffName ?? '').trim();

  const start = toDate(apt.startTime);
  const end = toDate(apt.endTime);
  const day = dayLabel(start);
  const from = timeLabel(start);
  const to = timeLabel(end);
  const window_ = from ? (to ? `${from} – ${to}` : from) : '';
  const duration = durationLabel(minutesBetween(start, end));

  const { value: scanValue, isShortCode } = ticketScanValue(apt);
  // Short codes are matched case-insensitively at lookup, so printing them
  // uppercase is both safe and far easier to read off paper. Tokens are matched
  // exactly and must be left alone.
  const codeForScanner = isShortCode ? scanValue.toUpperCase() : scanValue;
  const codeForHumans = isShortCode ? scanValue.toUpperCase() : '';

  const checkInUrl = ticketCheckInUrl(apt, ctx.origin);
  // Whatever the guest scans has to resolve. A full URL opens their page in one
  // tap; with no origin available the bare token still identifies the visit.
  const qrPayload = checkInUrl || String(apt.checkInToken ?? '').trim() || codeForScanner;

  const qr = qrPayload ? qrSvg(qrPayload, 118) : '';
  const barcode = codeForScanner ? code128Svg(codeForScanner, 46, 2) : '';

  const addOns = (ctx.addOnNames ?? []).map((s) => String(s ?? '').trim()).filter(Boolean);
  const stations = (ctx.resourceNames ?? []).map((s) => String(s ?? '').trim()).filter(Boolean);
  const price = money(ctx.priceCents);
  const deposit = money(apt.depositAmountCents);
  const depositLine = deposit
    ? `${deposit}${apt.depositStatus ? ` · ${titleCase(apt.depositStatus)}` : ''}`
    : '';

  const bookingNote = String(apt.notes ?? '').trim();
  const serviceNote = String(apt.serviceNotes ?? '').trim();

  const amenities = (ctx.amenities ?? [])
    .map((a) => {
      const name = String(a?.name ?? '').trim();
      if (!name) return '';
      const qty = Number(a?.quantity);
      const q = Number.isFinite(qty) && qty > 1 ? ` ×${qty}` : '';
      const st = String(a?.status ?? '').trim();
      return `<li><span>${esc(name)}${esc(q)}</span>${st ? `<span class="tag">${esc(titleCase(st))}</span>` : ''}</li>`;
    })
    .filter(Boolean)
    .join('');

  // ── Walk-in framing ──────────────────────────────────────────────────────
  // All of this collapses to empty strings for a normal appointment, so the
  // markup below is unchanged for every existing caller.
  const isWalkIn = String(ctx.kind ?? '') === 'walkin';
  const posNum = Number(ctx.queuePosition);
  const queuePos = Number.isFinite(posNum) && posNum > 0 ? Math.round(posNum) : 0;
  const waitNum = Number(ctx.queueWaitMinutes);
  const waitMins = Number.isFinite(waitNum) && waitNum > 0 ? Math.round(waitNum) : 0;
  const queueLine = !isWalkIn
    ? ''
    : String(ctx.queueNote ?? '').trim() ||
      (waitMins ? `About ${waitMins} minutes` : 'We will come get you shortly');
  const eyebrowLabel = isWalkIn ? 'Walk-in ticket' : 'Appointment ticket';
  const posLabel = queuePos ? `#${queuePos} in line` : 'In line';

  const statusLabel = isWalkIn
    ? (queuePos ? `In line · #${queuePos}` : 'In line')
    : titleCase(apt.checkInStatus === 'arrived' ? 'checked in' : apt.status) || 'Confirmed';

  // Printed on the guest stub, which is the half that leaves the building: the
  // address is there so someone holding the stub knows where to come back to,
  // and the phone so they can call without hunting for the number.
  const contactBits = [ctx.studioPhone, ctx.studioEmail, ctx.studioAddress]
    .map((s) => String(s ?? '').trim())
    .filter(Boolean)
    .map(esc)
    .join(' · ');

  const footBits = [
    esc(studioName),
    ctx.footerNote ? esc(String(ctx.footerNote).trim()) : '',
    `Printed ${esc(fmt(new Date(), { month: 'short', day: 'numeric', year: 'numeric', hour: 'numeric', minute: '2-digit' }))}`,
    ctx.hideBranding ? '' : 'Powered by ClarityFlow',
  ]
    .filter(Boolean)
    .join(' · ');

