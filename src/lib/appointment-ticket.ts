// src/lib/appointment-ticket.ts
//
// The printable appointment ticket — what comes out of the printer when the
// front desk checks a client in.
//
// It prints as ONE letter page holding TWO tickets separated by a tear line:
//
//   • STUDIO COPY — stays with the studio or clips to the station. Carries the
//     provider, the station, the booking notes, and a Code 128 barcode so the
//     ticket can be re-scanned later with an ordinary laser wedge scanner.
//   • GUEST STUB — torn off and handed to the client. Carries the confirmation
//     code in large type and a QR that opens their live check-in page, so they
//     can watch their own status, order from the lounge menu, and see what else
//     the studio offers while they wait.
//
// Why both a QR and a barcode: a phone camera reads a QR and cannot read a
// 1D barcode well; a cheap laser wedge scanner reads a 1D barcode and cannot
// read a QR at all. Printing only one guarantees that half the hardware a salon
// might own is useless. Both are generated by @/lib/scan-codes, whose output is
// verified by decoding it, not by looking at it.
//
// Like @/lib/tour-printouts, this file is framework-free and returns a complete,
// self-contained HTML string with inline CSS and no external assets, so it
// prints identically from any browser. It deliberately does NOT rely on the
// app's Tailwind classes: the print window is a blank document that has none of
// them, so anything styled by class name would come out as unstyled text.
//
// v2 adds WALK-IN tickets. A walk-in has no start time and no end time, so the
// time box used to print "Time to be confirmed" — true, but useless to someone
// standing in a lobby. Pass ctx.kind = 'walkin' with a queue position and a
// rough wait and the same page prints their place in line instead. Nothing
// changes for a caller that does not pass ctx.kind.
//
// Two rules that matter more than they look:
//   1. Everything user-provided is HTML-escaped. A client named
//      "A & B <Studio>" cannot break the layout or inject markup.
//   2. internalNotes is NEVER printed. The guest stub is handed to the guest,
//      and the studio copy gets left on counters. Only the booking note the
//      client themselves supplied, and the service note the provider recorded,
//      are safe to put on paper.

import { qrSvg, code128Svg } from '@/lib/scan-codes';
import { openPrintable } from '@/lib/tour-printouts';

/* ── The shapes this file reads ──────────────────────────────────────────── */

/** The fields we read off a tenants/{id}/appointments/{id} document. */
export interface TicketAppointment {
  id?: string | null;
  clientId?: string | null;
  clientName?: string | null;
  serviceId?: string | null;
  addOnIds?: string[] | null;
  staffId?: string | null;
  startTime?: any;
  endTime?: any;
  status?: string | null;
  checkInStatus?: string | null;
  checkInToken?: string | null;
  shortCode?: string | null;
  /** The note the client left when booking. Safe to print. */
  notes?: string | null;
  /** The note the provider recorded at checkout. Safe to print. */
  serviceNotes?: string | null;
  depositAmountCents?: number | null;
  depositStatus?: string | null;
  requiredResourceIds?: string[] | null;
}

/** One lounge order to list on the studio copy. Optional. */
export interface TicketAmenity {
  name?: string | null;
  quantity?: number | null;
  status?: string | null;
}

/**
 * Everything the ticket needs that does NOT live on the appointment document.
 *
 * The appointment stores IDs, not names — there is no serviceName and no price
 * on the document — so the caller resolves them from the collections it already
 * has in memory and passes the display strings in. That keeps this file free of
 * any Firestore dependency and makes it trivially testable.
 */
export interface TicketContext {
  studioName?: string | null;
  studioPhone?: string | null;
  studioEmail?: string | null;
  studioAddress?: string | null;

  clientName?: string | null;
  clientPhone?: string | null;
  serviceName?: string | null;
  addOnNames?: string[] | null;
  staffName?: string | null;
  resourceNames?: string[] | null;

  /** Service price in cents, if the caller wants it on the ticket. */
  priceCents?: number | null;

  /** Lounge orders already placed against this visit. */
  amenities?: TicketAmenity[] | null;

  /**
   * Origin for the guest QR, e.g. "https://studio.example.com". Defaults to the
   * current window's origin, which is correct in the browser and empty during
   * server rendering — in which case the QR falls back to the bare token, which
   * the scanner still understands.
   */
  origin?: string | null;

  /** Extra line in the footer, e.g. a tagline or a cancellation policy. */
  footerNote?: string | null;
  /** The business's brand colour (Studio look accents) and logo. */
  accent?: string | null;
  logoUrl?: string | null;
  /** 'letter' (default: studio copy + guest stub on one page) or 'receipt' (80 mm thermal: the guest stub alone). */
  size?: 'letter' | 'receipt' | null;
  /** Hide the "Powered by ClarityFlow" line. */
  hideBranding?: boolean;

  /**
   * What kind of visit this ticket is for. Omit it (or pass 'appointment') and
   * nothing below changes — every existing caller keeps the exact ticket it has
   * always printed.
   *
   * 'walkin' relabels three things for someone who arrived without a booking:
   * the eyebrow says "Walk-in ticket", the status pill says where they are in
   * the line, and the time box — which for a walk-in has no times in it at all
   * and would otherwise print the rather unhelpful "Time to be confirmed" —
   * carries their place in line and a softened wait instead.
   */
  kind?: 'appointment' | 'walkin' | null;

  /** 1-based place in the walk-in line. Ignored unless kind is 'walkin'. */
  queuePosition?: number | null;

  /**
   * Rough wait in minutes. Printed as "About 25 minutes", never as a countdown:
   * paper cannot tick down, and a guest holding a stub that promised 12 minutes
   * twenty minutes ago is a guest at the desk asking why.
   */
  queueWaitMinutes?: number | null;

  /** Overrides the wait sentence entirely, e.g. "Maya is ready for you now". */
  queueNote?: string | null;
}

/* ── Small helpers ───────────────────────────────────────────────────────── */

const esc = (v: any): string =>
  String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');

/**
 * Every date on an appointment has arrived from at least three places over the
 * life of this app: an ISO string, a Firestore Timestamp, and a real Date. Any
 * of them can also be null on an older document. This returns null rather than
 * an Invalid Date so that every caller below has to decide what to show, which
 * is the only way to be sure a half-filled appointment prints a dash instead of
 * the string "Invalid Date" on a ticket handed to a paying client.
 */
function toDate(value: any): Date | null {
  if (!value) return null;
  if (value instanceof Date) return isNaN(value.getTime()) ? null : value;
  if (typeof value === 'object' && typeof value.toDate === 'function') {
    try {
      const d = value.toDate();
      return d instanceof Date && !isNaN(d.getTime()) ? d : null;
    } catch {
      return null;
    }
  }
  if (typeof value === 'object' && typeof value.seconds === 'number') {
    const d = new Date(value.seconds * 1000);
    return isNaN(d.getTime()) ? null : d;
  }
  const d = new Date(value);
  return isNaN(d.getTime()) ? null : d;
}

const fmt = (d: Date | null, opts: Intl.DateTimeFormatOptions): string => {
  if (!d) return '';
  try {
    return d.toLocaleString('en-US', opts);
  } catch {
    return '';
  }
};

const dayLabel = (d: Date | null) =>
  fmt(d, { weekday: 'long', month: 'long', day: 'numeric', year: 'numeric' });
const timeLabel = (d: Date | null) => fmt(d, { hour: 'numeric', minute: '2-digit' });

const money = (cents?: number | null): string => {
  const n = Number(cents);
  if (!Number.isFinite(n) || n <= 0) return '';
  try {
    return (n / 100).toLocaleString('en-US', { style: 'currency', currency: 'USD' });
  } catch {
    return `$${(n / 100).toFixed(2)}`;
  }
};

const titleCase = (v: any): string =>
  String(v ?? '')
    .replace(/_/g, ' ')
    .replace(/\b\w/g, (m) => m.toUpperCase())
    .trim();

const minutesBetween = (a: Date | null, b: Date | null): number => {
  if (!a || !b) return 0;
  const mins = Math.round((b.getTime() - a.getTime()) / 60000);
  return mins > 0 ? mins : 0;
};

const durationLabel = (mins: number): string => {
  if (mins <= 0) return '';
  if (mins < 60) return `${mins} min`;
  const h = Math.floor(mins / 60);
  const m = mins % 60;
  return m ? `${h} hr ${m} min` : `${h} hr`;
};

/* ── What gets scanned ───────────────────────────────────────────────────── */

/**
 * Resolves the one value that both codes on this ticket will carry.
 *
 * The short code is preferred because it is short enough to read aloud over the
 * phone and to type by hand. When an older appointment has no short code we
 * fall back to the full check-in token, which the scanner also understands —
 * NOT to a truncated version of it, because a truncated token matches nothing
 * and would print a code that fails silently in the client's hand.
 */
export function ticketScanValue(apt: TicketAppointment): { value: string; isShortCode: boolean } {
  const code = String(apt.shortCode ?? '').trim();
  if (code) return { value: code, isShortCode: true };
  const token = String(apt.checkInToken ?? '').trim();
  return { value: token, isShortCode: false };
}

/**
 * The URL the guest's QR opens. Short codes are case-insensitive on lookup, but
 * check-in tokens are not, so the token is never case-folded.
 */
export function ticketCheckInUrl(apt: TicketAppointment, origin?: string | null): string {
  const token = String(apt.checkInToken ?? '').trim();
  if (!token) return '';
  const base = String(
    origin ?? (typeof window !== 'undefined' ? window.location.origin : '')
  ).replace(/\/+$/, '');
  return base ? `${base}/check-in/${token}` : '';
}

/* ── Markup fragments ────────────────────────────────────────────────────── */

function field(label: string, value: any): string {
  const v = String(value ?? '').trim();
  if (!v) return '';
  return `<div class="f"><div class="k">${esc(label)}</div><div class="v">${esc(v)}</div></div>`;
}

function pills(items: (string | null | undefined)[]): string {
  const list = items.map((s) => String(s ?? '').trim()).filter(Boolean);
  if (!list.length) return '';
  return list.map((s) => `<span class="pill">${esc(s)}</span>`).join('');
}

/**
 * The code block. Falls back to plain monospace text when a code cannot be
 * encoded, so a ticket is still usable rather than showing a blank gap — both
 * qrSvg and code128Svg return an empty string instead of emitting a symbol they
 * cannot encode correctly.
 */
function codeBlock(svg: string, human: string, caption: string, note: string): string {
  const art = svg
    ? `<div class="art">${svg}</div>`
    : `<div class="art art-empty"><span class="mono-big">${esc(human || '—')}</span></div>`;
  return `
    <div class="code">
      ${art}
      <div class="code-txt">
        <div class="k">${esc(caption)}</div>
        ${human ? `<div class="mono">${esc(human)}</div>` : ''}
        <div class="hint">${esc(note)}</div>
      </div>
    </div>`;
}

