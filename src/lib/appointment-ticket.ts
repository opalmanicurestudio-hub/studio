/**
 * Builds the ticket and opens it in a new tab with the print dialog ready.
 *
 * Returns false when a popup blocker stopped the window from opening, which is
 * common and silent — the caller should surface a toast telling the owner to
 * allow popups, otherwise pressing Print appears to do nothing at all.
 */
export function printAppointmentTicket(apt: TicketAppointment, ctx: TicketContext = {}): boolean {
  return openPrintable(appointmentTicketHtml(apt, ctx));
}
