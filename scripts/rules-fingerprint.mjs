// scripts/rules-fingerprint.mjs — writes src/lib/rules-fingerprint.ts: a short fingerprint of firestore.rules and
// storage.rules as they are in the repo, so HQ's launch check can tell whether the rules published in Firebase are the
// same. Runs before every build (package.json "prebuild"), so the fingerprint always matches the rules being deployed;
// also run it by hand after changing either file: node scripts/rules-fingerprint.mjs
// The normalizing must stay the same as src/lib/rules-normalize.ts (launch-readiness.verify checks they agree).
// It never stops a build: if anything goes wrong, the file is left as it was.
import { readFileSync, writeFileSync } from 'fs';
import { createHash } from 'crypto';

const normalize = (src) => String(src || '').replace(/\r\n?/g, '\n').split('\n').map((l) => l.replace(/[ \t]+$/, '')).join('\n').trim();
const fingerprint = (src) => createHash('sha256').update(normalize(src)).digest('hex').slice(0, 16);

try {
  const f = fingerprint(readFileSync('firestore.rules', 'utf8'));
  const s = fingerprint(readFileSync('storage.rules', 'utf8'));
  const out = `// src/lib/rules-fingerprint.ts — GENERATED by scripts/rules-fingerprint.mjs from firestore.rules and storage.rules.
// Don't edit by hand: it's rewritten before every build, or run the script after changing either rules file.
export const RULES_FINGERPRINT = { firestore: '${f}', storage: '${s}' } as const;
`;
  let now = ''; try { now = readFileSync('src/lib/rules-fingerprint.ts', 'utf8'); } catch {}
  if (now !== out) writeFileSync('src/lib/rules-fingerprint.ts', out);
  console.log('rules fingerprint: firestore', f, 'storage', s);
} catch (e) {
  console.warn('rules fingerprint: skipped,', e?.message || e);
}
